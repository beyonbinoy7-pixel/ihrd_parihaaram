-- =============================================================================
-- PARIHAARAM Database Schema Migration V1: Initial Relational Tables & Indexes
-- Authoritative schema compatible with PostgreSQL and H2 (PostgreSQL mode)
-- =============================================================================

-- 1. Colleges Table
CREATE TABLE colleges (
    id VARCHAR(20) PRIMARY KEY,
    code VARCHAR(20) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    hashtag VARCHAR(50) NOT NULL UNIQUE,
    location VARCHAR(255) NOT NULL,
    district VARCHAR(100) NOT NULL,
    lat DOUBLE PRECISION,
    lng DOUBLE PRECISION,
    principal VARCHAR(150),
    phone VARCHAR(50),
    email VARCHAR(150),
    established_year INT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    current_rank INT DEFAULT 1,
    performance_score DOUBLE PRECISION DEFAULT 85.0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. Users Table (Core Identity & Authentication)
CREATE TABLE users (
    id VARCHAR(50) PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    name VARCHAR(150) NOT NULL,
    role VARCHAR(50) NOT NULL,
    college_code VARCHAR(20) NOT NULL REFERENCES colleges(code),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 3. Students Table (Specialized Profile)
CREATE TABLE students (
    user_id VARCHAR(50) PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    student_id VARCHAR(50) NOT NULL UNIQUE,
    department VARCHAR(100) NOT NULL,
    year_of_study INT NOT NULL
);

-- 4. Complaints Table
CREATE TABLE complaints (
    id VARCHAR(64) PRIMARY KEY,
    ticket_id VARCHAR(50) NOT NULL UNIQUE,
    reporter_id VARCHAR(50) NOT NULL REFERENCES users(id),
    reporter_name VARCHAR(150) NOT NULL,
    reporter_email VARCHAR(150) NOT NULL,
    reporter_college_code VARCHAR(20) NOT NULL REFERENCES colleges(code),
    target_college_code VARCHAR(20) NOT NULL REFERENCES colleges(code),
    report_type VARCHAR(50) NOT NULL DEFAULT 'OWN_COLLEGE',
    category VARCHAR(100) NOT NULL,
    category_id VARCHAR(50) NOT NULL,
    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    building VARCHAR(100),
    floor VARCHAR(100),
    room VARCHAR(100),
    student_priority VARCHAR(20) NOT NULL DEFAULT 'MEDIUM',
    system_priority VARCHAR(20) NOT NULL DEFAULT 'MEDIUM',
    priority_score INT NOT NULL DEFAULT 50,
    priority_reason VARCHAR(255),
    status VARCHAR(50) NOT NULL DEFAULT 'SUBMITTED',
    sla_due_at TIMESTAMP,
    resolved_at TIMESTAMP,
    closed_at TIMESTAMP,
    reopened_at TIMESTAMP,
    resolution_description TEXT,
    resolution_by VARCHAR(150),
    reopen_reason TEXT,
    reopen_by VARCHAR(150),
    rating INT,
    student_feedback_comment TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 5. Complaint Evidence Table (Before / After / Reopen proof)
CREATE TABLE complaint_evidence (
    id VARCHAR(64) PRIMARY KEY,
    complaint_id VARCHAR(64) NOT NULL REFERENCES complaints(id) ON DELETE CASCADE,
    file_name VARCHAR(255) NOT NULL,
    stored_file_path VARCHAR(500) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    file_size BIGINT NOT NULL,
    evidence_type VARCHAR(50) NOT NULL DEFAULT 'BEFORE',
    uploaded_by VARCHAR(50) NOT NULL REFERENCES users(id),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 6. Complaint Status History Table (Authoritative Audit Timeline)
CREATE TABLE complaint_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_id VARCHAR(64) NOT NULL REFERENCES complaints(id) ON DELETE CASCADE,
    from_status VARCHAR(50),
    to_status VARCHAR(50) NOT NULL,
    actor_id VARCHAR(50) NOT NULL REFERENCES users(id),
    actor_name VARCHAR(150) NOT NULL,
    actor_role VARCHAR(50) NOT NULL,
    comment TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 7. Notifications Table
CREATE TABLE notifications (
    id VARCHAR(64) PRIMARY KEY,
    user_id VARCHAR(50) NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role VARCHAR(50) NOT NULL,
    title VARCHAR(200) NOT NULL,
    message TEXT NOT NULL,
    complaint_id VARCHAR(64),
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 8. Audit Logs Table (Append-only Security Event Ledger)
CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id VARCHAR(50) NOT NULL,
    actor_role VARCHAR(50) NOT NULL,
    action VARCHAR(100) NOT NULL,
    entity_type VARCHAR(100),
    entity_id VARCHAR(100),
    ip_address VARCHAR(50),
    metadata TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Performance & Isolation Indexes
CREATE INDEX idx_complaints_ticket_id ON complaints(ticket_id);
CREATE INDEX idx_complaints_reporter_id ON complaints(reporter_id);
CREATE INDEX idx_complaints_target_college ON complaints(target_college_code);
CREATE INDEX idx_complaints_status ON complaints(status);
CREATE INDEX idx_complaints_created_at ON complaints(created_at);
CREATE INDEX idx_history_complaint_id ON complaint_status_history(complaint_id);
CREATE INDEX idx_evidence_complaint_id ON complaint_evidence(complaint_id);
CREATE INDEX idx_notifications_user_id ON notifications(user_id);
CREATE INDEX idx_audit_logs_actor ON audit_logs(actor_id);
